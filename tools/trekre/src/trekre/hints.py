"""Facts about TREK.EXE 1.0 that static analysis cannot find on its own.

Segments and offsets are as in docs/findings.md (unrelocated). Anything not
listed here is still handled at run time by the interpreter; these hints
only make more of the program run as recompiled code.
"""

from __future__ import annotations

import struct

SHA256 = "1bc83431eeb9fd01"  # prefix of the TREK.EXE these hints were made for

# Far routines that never return (System unit: RunError entry points and Halt).
NORETURN = {(0x1D90, 0x01E9), (0x1D90, 0x01F0), (0x1D90, 0x01F3)}

# The EGAVGA driver's code starts 0A0h bytes into its segment; Graph calls
# it through a table of near pointers at offset 16h (29 entries).
DRIVER_CODE_SEG = 0x0AAB
DRIVER_TABLE = (0x16, 29)

# Instructions rewritten at run time. Each is split into its own block that
# is never recompiled, so the interpreter runs whatever bytes are there:
#  - the driver's "emulate" hook, a RET that Graph turns into a far JMP;
#  - Dos.Intr's INT instruction, whose number is patched before each call.
DYNAMIC = {(0x0AAB, 0x0010), (0x1521, 0x0099)}

# Code moved at run time before it executes: (source seg, off), (destination
# seg, off), length. Graph's initialisation shifts its internal driver
# interface down 6 bytes and runs it with CS=1C1F. The recompiler decodes the
# image as it is after these moves.
MOVED = [((0x1A0F, 0x2106), (0x1C1F, 0x0000), 0x1703)]


def seeds(image: bytes) -> list[tuple[int, int]]:
    off, count = DRIVER_TABLE
    base = DRIVER_CODE_SEG * 16 + off
    entries = struct.unpack_from(f"<{count}H", image, base)
    return sorted({(DRIVER_CODE_SEG, e) for e in entries} - DYNAMIC)


